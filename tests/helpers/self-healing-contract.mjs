import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';

export async function selfHealingContract(f) {
  const sent=await f.send(),path=`/publications/${sent.publicationId}/improvement`;
  const recipients=await f.query('SELECT id,worker_id FROM assignments WHERE publication_id=? ORDER BY worker_id',[sent.publicationId]);
  const rows=recipients.slice(0,3);
  assert.equal((await f.call(null,path)).status,401);
  assert.equal((await f.call('worker',path)).status,403);
  assert.equal((await f.call('foreign',path)).status,404);
  assert.equal((await f.call('owner',path,undefined,'bad-context')).status,409);
  assert.equal((await f.call('owner',path+'?org_id=other')).status,400);
  assert.equal((await f.call('auditor',path,{})).status,403);
  assert.equal((await f.call('owner',path,{extra:true})).status,400);
  assert.equal((await (await f.call('owner',path)).json()).signal,null);
  await f.answer(rows[0],false);await f.answer(rows[1],false);
  assert.equal(await f.process(),false);
  await f.answer(rows[2],true);
  const before=(await f.query('SELECT * FROM publications WHERE id=?',[sent.publicationId]))[0];
  assert.equal(await f.process(),true);assert.equal(await f.process(),false);
  let view=await (await f.call('owner',path)).json();
  assert.deepEqual(view.current,{assessed:3,matched:1,clarification:2,matchRate:33});
  assert.equal(view.signal.assessed,3);assert.equal(view.signal.matched,1);assert.equal(view.simulated,true);
  assert.equal(view.languages[0].language,'en');assert.equal(view.languages[0].assessed,3);
  assert.ok(view.suggestion.source.includes('north gate'));
  assert.equal((await f.call('auditor',path)).status,200);
  assert.equal((await f.call('owner',path,{})).status,200);
  assert.equal((await f.query("SELECT count(*) AS n FROM audit WHERE action='instruction.improvement_suggested'"))[0].n,1);
  await assert.rejects(f.query('UPDATE instruction_improvements SET matched=0 WHERE publication_id=?',[sent.publicationId]),/immutable/);
  await assert.rejects(f.query('DELETE FROM instruction_improvements WHERE publication_id=?',[sent.publicationId]),/immutable/);
  const another=await f.send();
  await assert.rejects(f.query(`INSERT INTO instruction_improvements VALUES(?,?,?,?,?,?,?,?)`,
    [another.publicationId,f.org,f.site,another.briefingId,3,1,2,new Date().toISOString()]),/scope or evidence mismatch/);
  const change={requestId:randomUUID(),title:'Clear gate instruction',source:'Close the north gate before the night shift. Keep the walkway clear.'};
  assert.equal((await f.call('auditor',path+'/draft',change)).status,403);
  assert.equal((await f.call('foreign',path+'/draft',change)).status,404);
  assert.equal((await f.call('owner',path+'/draft',{...change,extra:true})).status,400);
  await f.failAudit(true);
  assert.equal((await f.call('owner',path+'/draft',change)).status,503);
  assert.equal((await f.query('SELECT count(*) AS n FROM briefings WHERE id=?',[change.requestId]))[0].n,0);
  await f.failAudit(false);
  const accepted=await f.call('owner',path+'/draft',change);assert.equal(accepted.status,200);
  view=await accepted.json();assert.equal(view.followup.briefingId,change.requestId);assert.equal(view.followup.state,'draft');
  assert.equal(view.duplicate,false);
  const candidates=await f.call('owner',`/briefings/${change.requestId}/reverification?outcome=response&window=any`);
  assert.equal(candidates.status,200);assert.equal((await candidates.json()).total,3);
  assert.equal((await (await f.call('owner',path+'/draft',change)).json()).duplicate,true);
  assert.equal((await f.call('owner',path+'/draft',{...change,source:change.source+' Changed.'})).status,409);
  assert.equal((await f.call('owner',path+'/draft',{...change,requestId:randomUUID()})).status,409);
  await assert.rejects(f.query("UPDATE instruction_improvement_drafts SET request_hash=? WHERE publication_id=?",['a'.repeat(64),sent.publicationId]),/immutable/);
  await assert.rejects(f.query('DELETE FROM instruction_improvement_drafts WHERE publication_id=?',[sent.publicationId]),/immutable/);
  assert.deepEqual((await f.query('SELECT * FROM publications WHERE id=?',[sent.publicationId]))[0],before);
  const followup=await f.publishDraft(change.requestId,rows.map(row=>row.worker_id));
  const followupAssignments=await f.query('SELECT id,worker_id FROM assignments WHERE publication_id=? ORDER BY worker_id',[followup.id]);
  for(const row of followupAssignments)await f.answer(row,true);
  view=await (await f.call('owner',path)).json();
  assert.equal(view.followup.state,'published');assert.equal(view.followup.publicationId,followup.id);
  assert.equal(view.followup.counts.matchRate,100);assert.equal(view.followup.counts.assessed,3);assert.equal(view.signal.matchRate,33);
  await f.answer(rows[0],true);
  view=await (await f.call('owner',path)).json();assert.equal(view.current.assessed,3);assert.equal(view.current.matched,2);assert.equal(view.signal.matched,1);
  await f.removeWorker(rows[1].worker_id);
  view=await (await f.call('owner',path)).json();
  assert.equal(view.current.assessed,2);assert.equal(view.followup.counts.assessed,2);assert.equal(view.signal.assessed,3);
  assert.ok(!/answerText|phone|data_base64|worker_id/.test(JSON.stringify(view)));
  assert.deepEqual((await f.query('SELECT * FROM publications WHERE id=?',[sent.publicationId]))[0],before);
  const withdrawal=await f.call('owner',`/briefings/${change.requestId}/withdraw`,{requestId:randomUUID(),publicationId:followup.id,version:1,reason:'Synthetic follow-up review'});
  assert.equal(withdrawal.status,200);
  view=await (await f.call('owner',path)).json();
  assert.equal(view.followup.state,'withdrawn');assert.equal(view.followup.publicationId,followup.id);
}
